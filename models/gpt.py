  def __init__(self):
    super().__init__()
    self.token_embedding_table = nn.Embedding(vocab_size, n_embd) # each token directly reads off the logits for the next token from a lookup table
    self.position_embedding_table = nn.Embedding(block_size, n_embd)
    self.blocks = nn.Sequential(*[Block(n_embd, n_head) for _ in range(n_layer)])
    self.ln_f = nn.LayerNorm(n_embd) # final layer norm
    self.lm_head = nn.Linear(n_embd, vocab_size)

  def forward(self, idx, targets=None):
    B,T = idx.shape # B=batch, T=time
    # Both idx, targets are (B,T) dimension of tensors
    token_embd = self.token_embedding_table(idx) # (B,T,C(n_embd))
    pos_embd = self.position_embedding_table(torch.arange(T, device=device)) # (T,C)
    x  = token_embd + pos_embd # (B,T,C)
    x = self.blocks(x) # (B,T,C)
    x = self.ln_f(x) # (B,T,C)
    logits = self.lm_head(x) # (B,T,C(vocab_size))

    if targets is None:
      loss = None
    else:
      B, T, C = logits.shape
      logits = logits.view(B*T,C)
      targets = targets.view(B*T)
      loss = F.cross_entropy(logits, targets)

    return logits, loss

  def generate(self, idx, max_new_tokens):
    # idx is (B,T) array of indices in the current context
    for _ in range(max_new_tokens):
      # crop idx to the last block_size tokens
      idx_cond = idx[:, -block_size:]
      # get the predictions
      logits, loss = self(idx_cond)
      # take only last time step/prediction
      logits = logits[:, -1, :] # becomes (B, C)
      # using softmax to get probability distribution
      probs = F.softmax(logits, dim=-1)
      # sample from distribution
      idx_next  = torch.multinomial(probs, num_samples=1) #(B,1)
      # add new sampled index to the running sequence
      idx = torch.cat((idx, idx_next), dim =1 ) # (B, T+1)


    return idx